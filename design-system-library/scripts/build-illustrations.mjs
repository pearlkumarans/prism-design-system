#!/usr/bin/env node
/* =============================================================================
   build-illustrations.mjs

   Reads every *.svg from src/illustrations/source/ and assembles them into a
   single sprite at src/icons/illustrations.svg, where each <symbol> is named
   `illu-{filename-without-ext}` with the original viewBox preserved.

   Usage:  node scripts/build-illustrations.mjs
   ============================================================================= */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SOURCE_DIR = join(__dirname, '..', 'src', 'illustrations', 'source');
const OUTPUT_FILE = join(__dirname, '..', 'src', 'icons', 'illustrations.svg');

const files = readdirSync(SOURCE_DIR)
  .filter((f) => f.toLowerCase().endsWith('.svg'))
  .sort();

if (files.length === 0) {
  console.error(`No .svg files found in ${SOURCE_DIR}`);
  process.exit(1);
}

const symbols = files.map((file) => {
  const raw = readFileSync(join(SOURCE_DIR, file), 'utf8');
  const name = basename(file, extname(file)).toLowerCase().replace(/[^a-z0-9-]/g, '-');
  // Pull the opening <svg ...> attributes (we want viewBox) and the inner content.
  const openMatch = raw.match(/<svg([^>]*)>/);
  if (!openMatch) {
    console.warn(`Skipping ${file} — no <svg> tag.`);
    return '';
  }
  const attrs = openMatch[1];
  const viewBoxMatch = attrs.match(/viewBox="([^"]+)"/);
  const viewBox = viewBoxMatch ? viewBoxMatch[1] : '0 0 220 184';

  // Inner = everything between the opening <svg ...> and the closing </svg>.
  const inner = raw
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .trim();

  return `  <symbol id="illu-${name}" viewBox="${viewBox}">\n    ${inner}\n  </symbol>`;
}).filter(Boolean);

const sprite = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" style="display: none;">
  <!--
    UEMS Illustration Sprite
    Generated by scripts/build-illustrations.mjs from src/illustrations/source/.
    Each <symbol id="illu-{name}"> can be referenced via:
      <svg><use href="/illustrations.svg#illu-{name}"/></svg>
    or via the <ds-illustration name="{name}"></ds-illustration> custom element.

    Unlike icons, illustrations preserve their own multi-color fills (no
    currentColor inheritance). To add new ones, drop a .svg into the source
    directory and rerun this script.
  -->

${symbols.join('\n\n')}
</svg>
`;

writeFileSync(OUTPUT_FILE, sprite, 'utf8');
console.log(`Wrote ${files.length} illustrations to ${OUTPUT_FILE}`);
